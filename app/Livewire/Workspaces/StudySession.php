    public function resume(): void
    {
        $this->act(fn () => $this->sessions->resume($this->principal(), $this->sessionId));
    }

    /** The Pomodoro clock's next phase, now. */
    public function skip(): void
    {
        $this->act(fn () => $this->sessions->skip($this->principal(), $this->sessionId));
    }

    /** The Pomodoro countdown reached zero in the browser: show the next phase. */
    public function phaseEnded(): void
    {
        $this->dispatch('session-changed');
    }

    /** Opens App\Livewire\Workspaces\FlashcardEditor for a card on the session's topic, in its module. */
    #[On('session-new-card')]
    public function newFlashcard(): void
    {
        $session = $this->sessions->find($this->principal(), $this->sessionId);
        $this->dispatch('flashcard-new', topicId: $session->topicId, moduleId: $session->moduleId);
    }

    /** What the session is about: one of the course's topics, a new one in the session's module, or none. */
    public function editTopic(): void
    {
        $topicId = $this->sessions->find($this->principal(), $this->sessionId)->topicId;
        $this->open('topic');
        $this->topicChoice = $topicId ?? '';
    }

    /** The rail's topic, tapped: the session is about it now (the tutor reads it from its next message). */
    public function switchTopic(string $topicId): void
    {
        $now = null;
        $this->act(function () use ($topicId, &$now) {
            try {
                $topic = $this->topics->find($this->principal(), $topicId);
                $this->sessions->setTopic($this->principal(), $this->sessionId, $topic->id);
                $now = $topic->name;
            } catch (NotFound) {
                $this->error = 'That topic no longer exists.';
            }
        });
        $this->notice = $now === null ? null : "Now on {$now}.";
    }

    /** A question to keep, from the + menu: it goes to the module's questions (and to this session). */
    #[On('session-new-question')]
    public function newQuestion(): void
    {
        $this->open('question');
    }

    /** Opens a question already asked in this session so the student can get an AI answer or update its answer. */
    public function openQuestion(string $questionId): void
    {
        $by = $this->principal();
        try {
            $question = $this->questions->find($by, $questionId);
            if ($question->workspaceId !== $this->workspaceId) {
                return;
            }
        } catch (NotFound) {
            return;
        }
        $this->open('question');
        $this->editingQuestionId = $question->id;
        $this->questionText = $question->text;
        $this->questionAnswer = (string) ($question->answer ?? '');
    }

    public function quickAnswerQuestion(string $questionId): void
    {
        $this->openQuestion($questionId);
    }

    public function saveQuickAnswer(string $questionId, string $answer): void
    {
        $clean = trim($answer);
        if ($clean === '') {
            return;
        }
        $this->act(function () use ($questionId, $clean) {
            $this->questions->setStatus($this->principal(), $questionId, 'answered', mb_substr($clean, 0, Questions::MAX_ANSWER));
        }, 'Answer saved.');
        $this->dispatch('questions-changed');
    }

    public function generateConciseAnswer(string $questionId): void
    {
        $by = $this->principal();
        try {
            $question = $this->questions->find($by, $questionId);
        } catch (NotFound) {
            return;
        }
        $session = $this->sessions->find($by, $this->sessionId);
        $moduleId = $this->moduleIdOf($by, $session);
        $briefing = $this->briefings->forSession($by, $this->sessionId)->markdown;
        $briefingExcerpt = mb_substr($briefing, 0, 3_800);

        $recentChat = [];
        foreach (array_slice($this->chat->transcript($by, $this->sessionId), -6) as $turn) {
            $who = ($turn['role'] ?? '') === 'user' ? 'Student' : 'Tutor';
            $turnText = trim((string) ($turn['text'] ?? ''));
            if ($turnText !== '') {
                $recentChat[] = "{$who}: ".mb_substr($turnText, 0, 300);
            }
        }
        $chatBlock = $recentChat === [] ? '' : "\n\nRecent study session chat:\n".implode("\n", $recentChat);
        $thing = mb_substr("Question:\n{$question->text}\n\nContext:\n{$briefingExcerpt}{$chatBlock}", 0, Helper::MAX_THING);
        $task = 'Answer the question directly, simply, and concisely. Output ONLY the direct answer in 1 or 2 clear, question-oriented sentences (maximum 35 words). Do not include any background explanations, filler, or preamble.';

        try {
            $answer = $this->helper->quick($by, $task, $thing, $moduleId, $this->workspaceId, $session->folderId);
            $clean = mb_substr(trim($answer), 0, Questions::MAX_ANSWER);
            if ($clean !== '') {
                $this->act(function () use ($by, $questionId, $clean) {
                    $this->questions->setStatus($by, $questionId, 'answered', $clean);
                }, 'Answer saved.');
                $this->dispatch('questions-changed');
            }
        } catch (AppError $e) {
            $this->error = $e->getMessage();
        }
    }

