            'awaySince' => $session->pausedBy === 'away' ? $time($session->lastActivityAt) : null,
            'sideNote' => $this->sideNotes($by, $session, $module, $folder, $topic, $inside, $zone),
            'sideFile' => $this->sideFiles($by, $session, $module, $folder, $inside),
            'sideCards' => $this->sideCards($by, $session, $module, $folder, $topic, $inside, $this->flashcards->today($by)),
            'sideQuizzes' => $this->sideQuizzes($by, $session, $module, $zone),
            'sideQuestions' => $this->sideQuestions($by, $session, $module, $topic, $zone),
            'tutoring' => Tutoring::normalised($session->tutoring),
            'tutoringChoices' => Tutoring::CHOICES,
            'tutoringQuestions' => Tutoring::QUESTIONS,
        ]);
    }

    /**
     * Persistent side-by-side file data for the study session: files in the current folder/module (or workspace)
     * plus upload settings and metadata for the file viewer and dropdown popover.
     *
     * @param  ?list<string>  $inside
     * @return array{defaultUrl: string, defaultName: string, items: list<array{id: string, name: string, type: string, size: string, icon: string, iconUrl: string, inFolder: bool, used: bool, url: string, pageUrl: string}>, upload: array{url: string, placeType: string, placeId: string, accept: string, maxBytes: int, defaultIconUrl: string}}
     */
    private function sideFiles(Principal $by, SessionDetails $session, ?ModuleDetails $module, ?FolderDetails $folder, ?array $inside): array
    {
        $allFiles = $this->files->list($by, $this->workspaceId);
        $items = [];

        foreach ($allFiles as $file) {
            if ($file->trashedAt !== null) {
                continue;
            }
            $inScope = match (true) {
                $inside !== null => $file->folderId !== null && in_array($file->folderId, $inside, true),
                $module !== null => $file->moduleId === $module->id,
                default => true,
            };
            $items[] = [
                'id' => $file->id,
                'name' => $file->fileName(),
                'type' => $file->typeLabel(),
                'size' => $file->humanSize(),
                'icon' => $file->icon(),
                'iconUrl' => Icons::url($file->icon()),
                'inFolder' => $inScope,
                'used' => $session->uses("file:{$file->id}"),
                'url' => route('workspaces.files.show', [$this->workspaceId, $file->id, 'window' => 1, 'split' => 1]),
                'pageUrl' => route('workspaces.files.show', [$this->workspaceId, $file->id]),
            ];
        }

        usort($items, function (array $a, array $b) {
            if ($a['inFolder'] !== $b['inFolder']) {
                return $b['inFolder'] <=> $a['inFolder'];
            }
            if ($a['used'] !== $b['used']) {
                return $b['used'] <=> $a['used'];
            }

            return strnatcasecmp($a['name'], $b['name']);
        });

        $placeType = $folder !== null ? 'folder' : ($module !== null ? 'module' : 'workspace');
        $placeId = $folder?->id ?? $module?->id ?? $this->workspaceId;
        $extensions = array_map(fn (string $ext) => ".{$ext}", [...array_keys(FileTypes::TYPES), 'jpeg']);

        return [
            'defaultUrl' => $items[0]['url'] ?? '',
            'defaultName' => $items[0]['name'] ?? '',
            'items' => array_slice($items, 0, 80),
            'upload' => [
                'url' => route('api.v1.files.store'),
                'placeType' => $placeType,
                'placeId' => $placeId,
                'accept' => implode(',', $extensions),
                'maxBytes' => Files::maxBytes(),
                'defaultIconUrl' => Icons::url('file-text'),
            ],
        ];
    }

    /**
     * Persistent side-by-side note data for the study session: the session's own study note (matching WriteNoteTool)
     * plus existing notes in the current folder/module so the student can take notes beside the AI chat.
     *
     * @param  ?list<string>  $inside
     * @return array{defaultUrl: string, defaultTitle: string, newUrl: string, items: list<array{id: string, title: string, url: string}>}
     */
    private function sideNotes(Principal $by, SessionDetails $session, ?ModuleDetails $module, ?FolderDetails $folder, ?TopicDetails $topic, ?array $inside, string $zone): array
    {
        $on = $topic?->name ?? $folder?->name ?? $module?->title;
        $defaultTitle = mb_substr(implode(' · ', array_filter([
            'Study notes',
            $on,
            Carbon::parse($session->startedAt)->setTimezone($zone)->format('D j M'),
        ])), 0, Notes::MAX_TITLE);

        $place = $folder !== null ? "folder:{$folder->id}" : ($module !== null ? "module:{$module->id}" : null);
        $allNotes = $this->notes->list($by, $this->workspaceId);

        $defaultNote = null;
        try {
            $threadNoteId = LearnerTables::query(Guard::learner($by), 'engine_threads')->where('session_id', $session->id)->value('note_id');
            if ($threadNoteId !== null) {
                foreach ($allNotes as $note) {
                    if ($note->trashedAt === null && $note->id === $threadNoteId) {
                        $defaultNote = $note;
                        break;
                    }
                }
            }
        } catch (\Throwable) {
        }

        if ($defaultNote === null) {
            foreach ($allNotes as $note) {
                if ($note->trashedAt === null && $note->displayTitle() === $defaultTitle) {
                    $defaultNote = $note;
                    break;
                }
            }
        }

        $defaultTitle = $defaultNote?->displayTitle() ?? $defaultTitle;

        $defaultUrl = $defaultNote !== null
            ? route('workspaces.notes.show', [$this->workspaceId, $defaultNote->id, 'window' => 1, 'split' => 1])
            : route('workspaces.notes.create', [$this->workspaceId] + ($place === null ? [] : ['in' => $place]) + ['window' => 1, 'split' => 1, 'title' => $defaultTitle]);

        $newUrl = route('workspaces.notes.create', [$this->workspaceId] + ($place === null ? [] : ['in' => $place]) + ['window' => 1, 'split' => 1]);

        $items = [];
        foreach ($allNotes as $note) {
            if ($note->trashedAt !== null) {
                continue;
            }
            if ($defaultNote !== null && $note->id === $defaultNote->id) {
                continue;
            }
            $inScope = match (true) {
                $inside !== null => $note->folderId !== null && in_array($note->folderId, $inside, true),
                $module !== null => $note->moduleId === $module->id,
                default => true,
            };
            if ($inScope) {
                $items[] = [
                    'id' => $note->id,
                    'title' => $note->displayTitle(),
                    'url' => route('workspaces.notes.show', [$this->workspaceId, $note->id, 'window' => 1, 'split' => 1]),
                ];
            }
        }

        return [
            'defaultUrl' => $defaultUrl,
            'defaultTitle' => $defaultTitle,
            'newUrl' => $newUrl,
            'items' => array_slice($items, 0, 20),
        ];
    }

    /**
     * Flashcards for the side pane: cards belonging to this session, topic, folder or module.
     *
     * @param  ?list<string>  $inside
     * @return array{items: list<array{id: string, front: string, back: string, dueWords: string, isDue: bool, reviews: int, lastResult: ?string, topicId: ?string}>, total: int, due: int}
     */
    private function sideCards(Principal $by, SessionDetails $session, ?ModuleDetails $module, ?FolderDetails $folder, ?TopicDetails $topic, ?array $inside, string $today): array
    {
        $all = $this->flashcards->list($by, $this->workspaceId);
        $filtered = [];

        foreach ($all as $card) {
            $inScope = match (true) {
                $card->sessionId === $session->id => true,
                $topic !== null && $card->topicId === $topic->id => true,
                $inside !== null => $card->folderId !== null && in_array($card->folderId, $inside, true),
                $module !== null => $card->moduleId === $module->id,
                default => true,
            };
            if ($inScope) {
                $filtered[] = $card;
            }
        }

        if ($filtered === [] && $all !== []) {
            $filtered = $all;
        }

        $items = array_map(fn (FlashcardDetails $card) => [
            'id' => $card->id,
            'front' => $card->front,
            'back' => $card->back,
            'dueWords' => $card->dueWords($today),
            'isDue' => $card->due($today),
            'reviews' => $card->reviews,
            'lastResult' => $card->lastResult,
            'topicId' => $card->topicId,
        ], $filtered);

        return [
            'items' => array_slice($items, 0, 50),
            'total' => count($items),
            'due' => count(array_filter($items, fn (array $i) => $i['isDue'])),
        ];
    }

    /**
     * Quizzes and tests for the side pane: quizzes from this session and the course.
     *
     * @return array{items: list<array{id: string, kind: string, score: int, asked: int, right: int, finishedAt: string, isThisSession: bool, questions: list<array{asked: string, answer: string, result: string, right: string, fix: string, topic: ?string}>}>, count: int, avgScore: int}
     */
    private function sideQuizzes(Principal $by, SessionDetails $session, ?ModuleDetails $module, string $zone): array
    {
        $sessionQuizzes = $this->quizzes->forSession($by, $session->id);
        $moreQuizzes = $module !== null ? $this->quizzes->forModule($by, $module->id) : $this->quizzes->forWorkspace($by, $this->workspaceId);

        $seen = [];
        $combined = [];
        foreach ([...$sessionQuizzes, ...$moreQuizzes] as $quiz) {
            if (isset($seen[$quiz->id])) {
                continue;
            }
            $seen[$quiz->id] = true;
            $combined[] = $quiz;
        }

        $items = array_map(fn (QuizDetails $quiz) => [
            'id' => $quiz->id,
            'kind' => $quiz->kind,
            'score' => $quiz->score,
            'asked' => $quiz->asked,
            'right' => $quiz->right(),
            'durationWords' => $quiz->durationWords(),
            'paceWords' => $quiz->paceWords(),
            'finishedAt' => Carbon::parse($quiz->finishedAt)->setTimezone($zone)->diffForHumans(),
            'isThisSession' => $quiz->sessionId === $session->id,
            'questions' => $quiz->questions,
        ], $combined);

        $scores = array_column($items, 'score');

        return [
            'items' => array_slice($items, 0, 30),
            'count' => count($items),
            'avgScore' => $scores !== [] ? (int) round(array_sum($scores) / count($scores)) : 0,
        ];
    }

    /**
     * Questions registered for this session, topic, or module.
     *
     * @return array{items: list<array{id: string, text: string, status: string, statusLabel: string, answer: ?string, isThisSession: bool, askedAt: string}>, total: int, pending: int, answered: int}
     */
    private function sideQuestions(Principal $by, SessionDetails $session, ?ModuleDetails $module, ?TopicDetails $topic, string $zone): array
    {
        $all = $this->questions->list($by, $this->workspaceId);
        $filtered = [];

        foreach ($all as $q) {
            $inScope = match (true) {
                $q->sessionId === $session->id => true,
                $topic !== null && $q->topicId === $topic->id => true,
                $module !== null && $q->moduleId === $module->id => true,
                default => false,
            };
            if ($inScope) {
                $filtered[] = $q;
            }
        }

        usort($filtered, function (QuestionDetails $a, QuestionDetails $b) use ($session) {
            $order = ['stuck' => 0, 'pending' => 1, 'answered' => 2];
            $rankA = $order[$a->status] ?? 3;
            $rankB = $order[$b->status] ?? 3;
            if ($rankA !== $rankB) {
                return $rankA <=> $rankB;
            }
            $aThis = $a->sessionId === $session->id ? 0 : 1;
            $bThis = $b->sessionId === $session->id ? 0 : 1;
            if ($aThis !== $bThis) {
                return $aThis <=> $bThis;
            }

            return $b->askedAt <=> $a->askedAt;
        });

        $items = array_map(fn (QuestionDetails $q) => [
            'id' => $q->id,
            'text' => $q->text,
            'status' => $q->status,
            'statusLabel' => $q->statusLabel(),
            'answer' => $q->answer,
            'isThisSession' => $q->sessionId === $session->id,
            'askedAt' => Carbon::parse($q->askedAt)->setTimezone($zone)->diffForHumans(),
        ], $filtered);

        return [
            'items' => array_slice($items, 0, 40),
            'total' => count($items),
            'pending' => count(array_filter($items, fn (array $i) => in_array($i['status'], ['pending', 'stuck'], true))),
            'answered' => count(array_filter($items, fn (array $i) => $i['status'] === 'answered')),
        ];
    }

    /**
     * The topics this session touched, for its end screen: the one it is on, and those the tutor set, marked or proposed.
     *
     * @param  array{topics: list<string>}  $activity
     * @param  ?list<TopicDetails>  $all
     * @return list<TopicDetails>
     */
    private function touched(Principal $by, SessionDetails $session, array $activity, ?array $all = null): array
    {
        $all ??= $this->topics->list($by, $this->workspaceId);
        $ids = array_values(array_unique(array_filter([$session->topicId, ...$activity['topics']])));

        return array_values(array_filter($all, fn (TopicDetails $t) => in_array($t->id, $ids, true)));
    }

    /** The session's module: its own, or its topic's. */
    private function moduleIdOf(Principal $by, SessionDetails $session): ?string
    {
        if ($session->moduleId !== null || $session->topicId === null) {
            return $session->moduleId;
        }
        try {
            return $this->topics->find($by, $session->topicId)->moduleId;
        } catch (NotFound) {
            return null;
        }
    }

    /**
     * The notes and files for the panel, by place: in a module, only that
     * module's (its top level, then its folders in order, each with its
     * path), never another module's (the owner's review, 2026-09-27); in a
     * folder (Phase 9), only that folder's and its folders'. With no module,
     * every module's and the top level's, each apart. Anything used in the
     * briefing from elsewhere (chosen before) is listed apart, so it can be
     * taken out.
     *
     * @param  ?list<string>  $inside  the session's folder and those inside it
     * @return array{groups: list<array{key: string, title: ?string, depth: int, items: list<array>}>, alsoUsed: list<array>, count: int, used: int}
     */
    private function material(Principal $by, SessionDetails $session, ?ModuleDetails $module, ?FolderDetails $folder = null, ?array $inside = null): array
    {
        $fileColours = ['pdf' => 'red', 'document' => 'blue', 'slides' => 'orange', 'spreadsheet' => 'green', 'text' => 'pink', 'image' => 'purple'];
        $byPlace = [];
        foreach ($this->notes->list($by, $this->workspaceId) as $note) {
            $byPlace[$note->placeKey()][] = ['key' => "note:{$note->id}", 'icon' => 'file-text', 'colour' => 'blue', 'name' => $note->displayTitle(), 'url' => route('workspaces.notes.show', [$this->workspaceId, $note->id]), 'type' => 'Note'];
        }
        foreach ($this->files->list($by, $this->workspaceId) as $file) {
            $byPlace[$file->placeKey()][] = ['key' => "file:{$file->id}", 'icon' => $file->icon(), 'colour' => $fileColours[$file->kind] ?? 'teal', 'name' => $file->fileName(), 'url' => route('workspaces.files.show', [$this->workspaceId, $file->id]), 'type' => $file->typeLabel()];
        }

        // The places to show, in order: [key, title, depth].
        $folders = $this->folders->tree($by, $this->workspaceId);
        $names = [];
        $places = function (?string $moduleId, ?string $title) use ($folders, &$names): array {
            $list = [[$moduleId === null ? "workspace:{$this->workspaceId}" : "module:{$moduleId}", $title, 0]];
            foreach ($folders as $folder) {
                if ($folder->moduleId !== $moduleId) {
                    continue;
                }
                $names[$folder->id] = ($folder->parentId !== null ? ($names[$folder->parentId] ?? '').' › ' : ($title !== null ? $title.' › ' : '')).$folder->name;
                $list[] = ["folder:{$folder->id}", $names[$folder->id], $folder->depth];
            }

            return $list;
        };
        $order = [];
        if ($folder !== null && $inside !== null) {
            // The folder itself, then the folders inside it, each with its path from the folder.
            $order = [["folder:{$folder->id}", null, 0]];
            $paths = [$folder->id => ''];
            foreach ($folders as $each) {
                if ($each->id !== $folder->id && in_array($each->id, $inside, true)) {
                    $paths[$each->id] = ltrim(($paths[$each->parentId] ?? '').' › '.$each->name, ' ›');
                    $order[] = ["folder:{$each->id}", $paths[$each->id], $each->depth - $folder->depth];
                }
            }
        } elseif ($module !== null) {
            $order = $places($module->id, null);
        } else {
            foreach ($this->modules->list($by, $this->workspaceId) as $each) {
                array_push($order, ...$places($each->id, $each->title));
            }
            array_push($order, ...$places(null, 'Notes & files'));
        }

        $groups = [];
        $shown = [];
        foreach ($order as [$key, $title, $depth]) {
            if (($byPlace[$key] ?? []) === []) {
                continue;
            }
            $groups[] = ['key' => $key, 'title' => $title, 'depth' => $depth, 'items' => $byPlace[$key]];
            foreach ($byPlace[$key] as $item) {
                $shown[$item['key']] = true;
            }
        }
        $alsoUsed = [];
        foreach ($byPlace as $items) {
            foreach ($items as $item) {
                if (! isset($shown[$item['key']]) && $session->uses($item['key'])) {
                    $alsoUsed[] = $item;
                }
            }
        }
        $all = [...array_merge([], ...array_column($groups, 'items')), ...$alsoUsed];

        return [
            'groups' => $groups,
            'alsoUsed' => $alsoUsed,
            'count' => count($shown),
            'used' => count(array_filter($all, fn ($item) => $session->uses($item['key']))),
        ];
    }

    /** The chat's summary and checkpoint into the session's record, once; an engine that fails leaves them for later. */
    private function wrapUp(Principal $by): bool
    {
        try {
            return $this->chat->wrapUp($by, $this->sessionId) !== null;
        } catch (Unprocessable|NotFound) {
            return false;
        }
    }

    private function act(callable $action, ?string $notice = null): void
    {
        $this->error = null;
        try {
            $action();
            $this->notice = $notice;
        } catch (Conflict $e) {
            $this->error = $e->getMessage();
        }
        $this->dispatch('session-changed');
    }

    /** The course's topic with that name, or a new one in $moduleId (and the session's folder, while it is there). */
    private function newTopicId(Principal $by, ?string $moduleId, ?string $folderId = null): string
    {
        $name = trim($this->newTopic);
        $same = collect($this->topics->list($by, $this->workspaceId))->first(fn ($t) => mb_strtolower($t->name) === mb_strtolower($name));
        if ($same !== null) {
            return $same->id;
        }
        try {
            return $this->topics->create($by, $this->workspaceId, $name, $moduleId, $folderId)->id;
        } catch (NotFound) {
            return $this->topics->create($by, $this->workspaceId, $name, $moduleId)->id;
        }
    }

    /** The folder the session studies in, while it is there and in the session's module. */
    private function folderOf(Principal $by, SessionDetails $session, ?ModuleDetails $module): ?FolderDetails
    {
        if ($session->folderId === null || $module === null) {
            return null;
        }
        try {
            $folder = $this->folders->find($by, $session->folderId);
        } catch (NotFound) {
            return null;
        }

        return $folder->moduleId === $module->id ? $folder : null;
    }

    private function open(string $mode): void
    {
        $this->close();
        $this->mode = $mode;
        $this->dispatch('session-dialog-open');
    }

    private function principal(): Principal
    {
        return $this->principals->fromRequest(request());
    }
