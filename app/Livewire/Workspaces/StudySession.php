    public function openQuizConfigure(?string $kind = 'custom'): void
    {
        $this->quizKind = $kind ?? 'custom';
        if ($this->quizKind === 'quick') {
            $this->quizCount = 3;
            $this->quizFormat = 'mix';
        }
        $this->quizView = 'configure';
    }

    public function cancelQuiz(): void
    {
        $this->quizView = 'idle';
        $this->activeQuizQuestions = [];
        $this->activeQuizAnswers = [];
        $this->activeQuizIndex = 0;
        $this->quizStartedAt = null;
        $this->quizStartEpoch = null;
    }

    public function startQuickRecap(): void
    {
        $this->quizKind = 'quick';
        $this->quizCount = 3;
        $this->quizFormat = 'mix';
        $this->quizLevel = 'medium';
        $this->generateAndStartQuiz();
    }

    public function startConfiguredQuiz(): void
    {
        $this->quizCount = max(2, min(15, (int) $this->quizCount));
        if (! in_array($this->quizFormat, ['best', 'short', 'write', 'mix'], true)) {
            $this->quizFormat = 'mix';
        }
        if (! in_array($this->quizLevel, ['easy', 'medium', 'hard'], true)) {
            $this->quizLevel = 'medium';
        }
        $this->generateAndStartQuiz();
    }

    public function generateAndStartQuiz(): void
    {
        $this->quizView = 'generating';
        $by = $this->principal();
        $session = $this->sessions->find($by, $this->sessionId);
        $topic = null;
        if ($session->topicId !== null) {
            try {
                $topic = $this->topics->find($by, $session->topicId);
            } catch (NotFound) {
                // Topic removed since
            }
        }
        $moduleId = $this->moduleIdOf($by, $session);
        $topicName = $topic?->name ?? 'Course Topics';
        $briefing = $this->briefings->forSession($by, $this->sessionId)->markdown;
        $briefingExcerpt = mb_substr($briefing, 0, 3_000);

        $typeDesc = match ($this->quizFormat) {
            'best' => 'All questions MUST be "choose the best" (Multiple Choice / MCQ) with 4 distinct options labeled A, B, C, D.',
            'short' => 'All questions MUST be "short answer" requiring 1 or 2 concise sentences.',
            'write' => 'All questions MUST be "write" requiring an in-depth explanatory conceptual answer.',
            default => 'A balanced "mix" of Multiple Choice (best), Short answer (short), and Written explanation (write) questions.',
        };

        $levelDesc = match ($this->quizLevel) {
            'easy' => 'Foundational recall, clear definitions, and direct terminology.',
            'hard' => 'Advanced scenarios, deep architectural reasoning, and edge-case analysis.',
            default => 'Core conceptual understanding and practical application.',
        };

        $task = "Generate a {$this->quizCount}-question study quiz for the topic \"{$topicName}\".
Question requirements:
- Question count: exactly {$this->quizCount} questions.
- Question format: {$typeDesc}
- Difficulty level: {$levelDesc}

OUTPUT FORMAT:
Output ONLY a valid JSON array of {$this->quizCount} objects with no markdown fences, no preamble, and no extra commentary.
Schema for each object:
{
  \"type\": \"best\"|\"short\"|\"write\",
  \"asked\": \"Question text here\",
  \"options\": {\"A\": \"First option\", \"B\": \"Second option\", \"C\": \"Third option\", \"D\": \"Fourth option\"},
  \"right\": \"Correct answer (Letter A/B/C/D if type is best, or ideal concise answer if short/write)\",
  \"explanation\": \"1-2 concise sentences explaining why this answer is right and what principle it tests.\",
  \"topic\": \"{$topicName}\"
}";

        $thing = "Topic: {$topicName}\n\nCourse Context:\n{$briefingExcerpt}";

        $parsedQuestions = [];
        try {
            $raw = $this->helper->quick($by, $task, $thing, $moduleId, $this->workspaceId, $session->folderId, maxTokens: 1_500);
            $clean = trim($raw);
            if (str_starts_with($clean, '```')) {
                $clean = preg_replace('/^```(?:json)?\s*/i', '', $clean);
                $clean = preg_replace('/\s*```$/', '', $clean);
                $clean = trim($clean);
            }
            if (preg_match('/\[\s*\{.*\}\s*\]/s', $clean, $matches)) {
                $clean = $matches[0];
            }
            $decoded = json_decode($clean, true);
            if (is_array($decoded) && $decoded !== []) {
                foreach (array_values($decoded) as $idx => $item) {
                    if (! isset($item['asked']) || trim((string) $item['asked']) === '') {
                        continue;
                    }
                    $type = in_array($item['type'] ?? '', ['best', 'short', 'write'], true) ? $item['type'] : 'best';
                    $options = is_array($item['options'] ?? null) ? $item['options'] : [];
                    if ($type === 'best' && count($options) < 2) {
                        $options = ['A' => 'Option A', 'B' => 'Option B', 'C' => 'Option C', 'D' => 'Option D'];
                    }
                    $parsedQuestions[] = [
                        'id' => $idx + 1,
                        'type' => $type,
                        'asked' => trim((string) $item['asked']),
                        'options' => $options,
                        'right' => trim((string) ($item['right'] ?? 'A')),
                        'explanation' => trim((string) ($item['explanation'] ?? 'Tests core concepts of this topic.')),
                        'topic' => $item['topic'] ?? $topicName,
                    ];
                }
            }
        } catch (\Throwable $e) {
            // Fallback gracefully if AI is unavailable or produces invalid JSON
        }

        if ($parsedQuestions === []) {
            $parsedQuestions = [
                [
                    'id' => 1,
                    'type' => 'best',
                    'asked' => "What is the primary objective of {$topicName}?",
                    'options' => [
                        'A' => 'To abstract resources and provide consistent services',
                        'B' => 'To replace hardware with software emulation',
                        'C' => 'To eliminate concurrency completely',
                        'D' => 'To bypass operating system protection layers',
                    ],
                    'right' => 'A',
                    'explanation' => 'The primary role is resource abstraction, management, and protection.',
                    'topic' => $topicName,
                ],
                [
                    'id' => 2,
                    'type' => 'short',
                    'asked' => "Explain how {$topicName} balances performance against safety.",
                    'options' => [],
                    'right' => 'By isolating processes while providing controlled system calls and fair scheduling.',
                    'explanation' => 'Isolation prevents interference while scheduled access ensures high throughput.',
                    'topic' => $topicName,
                ],
                [
                    'id' => 3,
                    'type' => 'write',
                    'asked' => "Describe one key challenge in designing {$topicName} and how it is addressed.",
                    'options' => [],
                    'right' => 'Managing shared resources without deadlocks or starvation through arbitration policies.',
                    'explanation' => 'Fair arbitration guarantees progress while preserving safety invariants.',
                    'topic' => $topicName,
                ],
            ];
        }

        $this->activeQuizQuestions = $parsedQuestions;
        $this->activeQuizAnswers = array_fill(0, count($parsedQuestions), '');
        $this->activeQuizIndex = 0;
        $this->quizStartedAt = CarbonImmutable::now('UTC')->toIso8601ZuluString('microsecond');
        $this->quizStartEpoch = time();
        $this->quizSavedAsQuestions = [];
        $this->quizView = 'taking';
    }

    public function selectQuizOption(int $qIndex, string $optionKey): void
    {
        $this->activeQuizAnswers[$qIndex] = $optionKey;

        if ($qIndex < count($this->activeQuizQuestions) - 1) {
            $this->activeQuizIndex = $qIndex + 1;
        }
    }

    public function nextQuizQuestion(): void
    {
        if ($this->activeQuizIndex < count($this->activeQuizQuestions) - 1) {
            $this->activeQuizIndex++;
        }
    }

    public function prevQuizQuestion(): void
    {
        if ($this->activeQuizIndex > 0) {
            $this->activeQuizIndex--;
        }
    }

    public function goToQuizQuestion(int $index): void
    {
        if ($index >= 0 && $index < count($this->activeQuizQuestions)) {
            $this->activeQuizIndex = $index;
        }
    }

    public function allQuestionsAnswered(): bool
    {
        if ($this->activeQuizQuestions === []) {
            return false;
        }

        foreach ($this->activeQuizQuestions as $idx => $q) {
            $answer = trim((string) ($this->activeQuizAnswers[$idx] ?? ''));
            if ($answer === '') {
                return false;
            }
        }

        return true;
    }

    public function submitQuiz(int $clientDuration = 0): void
    {
        if ($this->activeQuizQuestions === []) {
            $this->quizView = 'idle';

            return;
        }

        $this->quizView = 'grading';
        $by = $this->principal();
        $session = $this->sessions->find($by, $this->sessionId);
        $topicName = $this->activeQuizQuestions[0]['topic'] ?? null;
        $durationSeconds = max(1, $clientDuration > 0 ? $clientDuration : (time() - ($this->quizStartEpoch ?? time())));

        $graded = [];
        foreach ($this->activeQuizQuestions as $idx => $q) {
            $studentAns = trim((string) ($this->activeQuizAnswers[$idx] ?? ''));
            $type = $q['type'];
            $right = $q['right'];
            $explanation = $q['explanation'];

            if ($type === 'best') {
                $isCorrect = mb_strtoupper($studentAns) === mb_strtoupper($right);
                if (! $isCorrect && isset($q['options'][$right])) {
                    $isCorrect = mb_strtolower($studentAns) === mb_strtolower($q['options'][$right]);
                }
                $result = $isCorrect ? 'correct' : 'incorrect';
                $rightText = isset($q['options'][$right]) ? "{$right}: {$q['options'][$right]}" : $right;
                $userAnswerText = isset($q['options'][$studentAns]) ? "{$studentAns}: {$q['options'][$studentAns]}" : ($studentAns ?: '(No answer selected)');
                $fix = $isCorrect
                    ? "Correct! {$explanation}"
                    : "The correct choice is {$rightText}. {$explanation}";

                $graded[] = [
                    'asked' => $q['asked'],
                    'answer' => $userAnswerText,
                    'result' => $result,
                    'right' => $rightText,
                    'fix' => $fix,
                    'type' => $type,
                    'topic' => $q['topic'] ?? $topicName,
                ];
            } else {
                if ($studentAns === '') {
                    $graded[] = [
                        'asked' => $q['asked'],
                        'answer' => '(No answer written)',
                        'result' => 'incorrect',
                        'right' => $right,
                        'fix' => "No answer was provided. Key concept: {$right}. {$explanation}",
                        'type' => $type,
                        'topic' => $q['topic'] ?? $topicName,
                    ];
                } else {
                    $task = "Grade the student's answer to this question.
Question: {$q['asked']}
Correct concept / rubric: {$right}
Student's answer: {$studentAns}

Evaluate fairly:
- If the student accurately captures the core concept, result is 'correct'.
- If the student gets some parts right but misses important aspects, result is 'partial'.
- If incorrect, result is 'incorrect'.

OUTPUT FORMAT:
Output ONLY a valid JSON object:
{
  \"result\": \"correct\"|\"partial\"|\"incorrect\",
  \"fix\": \"1-2 concise sentences explaining why the correct answer is right and giving constructive feedback.\"
}";
                    $thing = "Question: {$q['asked']}\nStudent answer: {$studentAns}\nIdeal: {$right}";
                    $result = 'correct';
                    $fix = $explanation;
                    try {
                        $aiEval = $this->helper->quick($by, $task, $thing, $session->moduleId, $this->workspaceId, $session->folderId);
                        if (preg_match('/\{.*\}/s', $aiEval, $m)) {
                            $dec = json_decode($m[0], true);
                            if (is_array($dec)) {
                                $result = in_array($dec['result'] ?? '', ['correct', 'partial', 'incorrect'], true) ? $dec['result'] : 'correct';
                                $fix = trim((string) ($dec['fix'] ?? $explanation));
                            }
                        }
                    } catch (\Throwable $e) {
                        $result = mb_strlen($studentAns) > 15 ? 'correct' : 'partial';
                        $fix = $explanation;
                    }

                    $graded[] = [
                        'asked' => $q['asked'],
                        'answer' => $studentAns,
                        'result' => $result,
                        'right' => $right,
                        'fix' => $fix,
                        'type' => $type,
                        'topic' => $q['topic'] ?? $topicName,
                    ];
                }
            }
        }

        $now = CarbonImmutable::now('UTC');
        $startedAt = $clientDuration > 0
            ? $now->subSeconds($durationSeconds)->toIso8601ZuluString('microsecond')
            : ($this->quizStartedAt ?? $now->subSeconds($durationSeconds)->toIso8601ZuluString('microsecond'));

        $recordInput = [
            'kind' => 'quiz',
            'topic' => $topicName,
            'questions' => array_map(fn ($g) => [
                'asked' => $g['asked'],
                'answer' => $g['answer'],
                'result' => $g['result'],
                'right' => $g['right'],
                'fix' => $g['fix'],
                'topic' => $g['topic'],
            ], $graded),
            'started_at' => $startedAt,
        ];

        $savedQuiz = $this->quizzes->record($by, $this->sessionId, $recordInput);

        $durWords = $savedQuiz->durationWords();
        $paceWords = $savedQuiz->paceWords();
        $paceFeedback = match (true) {
            $durationSeconds / max(1, count($graded)) < 20 => '⚡ Rapid recall pace',
            $durationSeconds / max(1, count($graded)) < 45 => '🎯 Steady, focused pace',
            default => '🔍 Thorough, deliberate pace',
        };

        $this->latestQuizResult = [
            'id' => $savedQuiz->id,
            'score' => $savedQuiz->score,
            'asked' => $savedQuiz->asked,
            'right' => $savedQuiz->right(),
            'durationSeconds' => $durationSeconds,
            'durationWords' => $durWords,
            'paceWords' => $paceWords,
            'paceFeedback' => $paceFeedback,
            'questions' => $graded,
        ];

        $this->quizSavedAsQuestions = [];
        $this->quizView = 'reviewed';
        $this->dispatch('quizzes-changed');
    }

    public function turnQuizQuestionIntoQuestion(string $asked, ?string $answer = null, ?string $topicName = null): void
    {
        $asked = trim($asked);
        if ($asked === '') {
            return;
        }
        $by = $this->principal();
        $session = $this->sessions->find($by, $this->sessionId);
        $topicId = $session->topicId;
        if ($topicId === null && $topicName !== null) {
            $matched = collect($this->topics->list($by, $this->workspaceId))->first(fn ($t) => mb_strtolower($t->name) === mb_strtolower($topicName));
            $topicId = $matched?->id;
        }
        $moduleId = $this->moduleIdOf($by, $session);

        try {
            $question = $this->questions->ask($by, $this->workspaceId, $asked, $topicId, $moduleId, $session->id);
