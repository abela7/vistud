    {
        $this->act(function () use ($key, $value) {
            $session = $this->sessions->find($this->principal(), $this->sessionId);
            $current = Tutoring::normalised($session->tutoring);
            if (isset(Tutoring::CHOICES[$key][$value])) {
                $current[$key] = $value;
                $this->sessions->setTutoring($this->principal(), $this->sessionId, $current);
                $this->dispatch('session-changed');
            } elseif ($key === 'custom_do' || $key === 'custom_dont') {
