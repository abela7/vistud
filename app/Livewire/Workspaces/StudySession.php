        $this->topics = $topics;
        $this->modules = $modules;
        $this->notes = $notes;
        $this->files = $files;
        $this->principals = $principals;
    }

    public function mount(string $workspaceId, string $sessionId): void
    {
        [$this->workspaceId, $this->sessionId] = [$workspaceId, $sessionId];
        try {
            $scope = Guard::learner($this->principal());
            $noteId = LearnerTables::query($scope, 'engine_threads')->where('session_id', $sessionId)->value('note_id');
            if ($noteId !== null) {
                $this->activeNoteId = (string) $noteId;
            }
        } catch (\Throwable) {
        }
    }

    /** Sets the active note currently opened beside the session chat, updating the engine thread's study note. */
    public function setActiveNote(string $noteId): void
    {
        $this->activeNoteId = $noteId;
        try {
            $scope = Guard::learner($this->principal());
            $updated = LearnerTables::query($scope, 'engine_threads')
                ->where('session_id', $this->sessionId)
                ->update(['note_id' => $noteId, 'updated_at' => now()]);
            if ($updated === 0) {
                $model = $this->settings->get($this->principal())->tutorModel;
                LearnerTables::insert($scope, 'engine_threads', [
                    'id' => Ids::new(),
                    'workspace_id' => $this->workspaceId,
                    'session_id' => $this->sessionId,
                    'model' => $model,
                    'note_id' => $noteId,
                    'created_at' => now(),
                    'updated_at' => now(),
                ]);
            }
        } catch (\Throwable) {
        }
    }

